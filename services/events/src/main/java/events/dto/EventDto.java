package events.dto;

import java.math.BigDecimal;
import java.time.LocalDateTime;

import events.entity.Event;

public class EventDto {

    // Fields exposed in the JSON payload
    private Integer id;                     // generated by the database; ignored on create
    private String title;
    private String description;
    private Integer organiserId;            // user id of the organiser who owns the event
    private String location;
    private LocalDateTime startDateTime;    // ISO-8601, e.g. 2026-11-01T19:00:00
    private LocalDateTime endDateTime;      // must be after startDateTime
    private Integer capacity;               // remaining places; decremented on each signup
    private Integer maxCapacity;             // initial capacity; signups so far = maxCapacity - capacity
    private Integer minSignUps;              // minimum signups required before expiresAt
    private LocalDateTime expiresAt;         // event is auto-cancelled if minSignUps is not reached
    private BigDecimal ticketPrice;         // copied into Booking.totalAmount on signup
    private String currency;                // e.g. "SGD"
    private String status;                  // "ACTIVE" (default) allows signups; any other value blocks them
    private LocalDateTime createdAt;        // set by the service
    private LocalDateTime updatedAt;        // set by the service

    // No-args constructor required by Jackson to deserialize request bodies
    public EventDto() {
    }

    // Mapping: entity -> DTO (used for every response)
    public static EventDto from(Event event) {
        EventDto dto = new EventDto();
        dto.id = event.getId() == null ? null : event.getId().intValue();
        dto.title = event.getTitle();
        dto.description = event.getDescription();
        dto.organiserId = event.getOrganiserId();
        dto.location = event.getLocation();
        dto.startDateTime = event.getStartDateTime();
        dto.endDateTime = event.getEndDateTime();
        dto.capacity = event.getCapacity();
        dto.maxCapacity = event.getMaxCapacity();
        dto.minSignUps = event.getMinSignUps();
        dto.expiresAt = event.getExpiresAt();
        dto.ticketPrice = event.getTicketPrice();
        dto.currency = event.getCurrency();
        dto.status = event.getStatus();
        dto.createdAt = event.getCreatedAt();
        dto.updatedAt = event.getUpdatedAt();
        return dto;
    }

    // Mapping: DTO -> new entity (used on create)
    // id, createdAt and updatedAt are deliberately not copied: the database and the service set them.
    public Event toEntity() {
        Event event = new Event();
        event.setTitle(title);
        event.setDescription(description);
        event.setOrganiserId(organiserId);
        event.setLocation(location);
        event.setStartDateTime(startDateTime);
        event.setEndDateTime(endDateTime);
        event.setCapacity(capacity);
        event.setMaxCapacity(maxCapacity);
        event.setMinSignUps(minSignUps);
        event.setExpiresAt(expiresAt);
        event.setTicketPrice(ticketPrice);
        event.setCurrency(currency);
        event.setStatus(status);
        return event;
    }

    // Getters and setters (used by Jackson for JSON binding)
    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public Integer getOrganiserId() {
        return organiserId;
    }

    public void setOrganiserId(Integer organiserId) {
        this.organiserId = organiserId;
    }

    public String getLocation() {
        return location;
    }

    public void setLocation(String location) {
        this.location = location;
    }

    public LocalDateTime getStartDateTime() {
        return startDateTime;
    }

    public void setStartDateTime(LocalDateTime startDateTime) {
        this.startDateTime = startDateTime;
    }

    public LocalDateTime getEndDateTime() {
        return endDateTime;
    }

    public void setEndDateTime(LocalDateTime endDateTime) {
        this.endDateTime = endDateTime;
    }

    public Integer getCapacity() {
        return capacity;
    }

    public void setCapacity(Integer capacity) {
        this.capacity = capacity;
    }

    public Integer getMaxCapacity() {
        return maxCapacity;
    }

    public void setMaxCapacity(Integer maxCapacity) {
        this.maxCapacity = maxCapacity;
    }

    public Integer getMinSignUps() {
        return minSignUps;
    }

    public void setMinSignUps(Integer minSignUps) {
        this.minSignUps = minSignUps;
    }

    public LocalDateTime getExpiresAt() {
        return expiresAt;
    }

    public void setExpiresAt(LocalDateTime expiresAt) {
        this.expiresAt = expiresAt;
    }

    public BigDecimal getTicketPrice() {
        return ticketPrice;
    }

    public void setTicketPrice(BigDecimal ticketPrice) {
        this.ticketPrice = ticketPrice;
    }

    public String getCurrency() {
        return currency;
    }

    public void setCurrency(String currency) {
        this.currency = currency;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}
