package events.entity;

import java.math.BigDecimal;
import java.time.LocalDateTime;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;


@Entity
@Table(name = "events")
public class Event {

    // Identity
    // Concurrency is handled with pessimistic locking: every write first locks the row with
    // SELECT ... FOR UPDATE (EventRepository.findByIdForUpdate), so concurrent writers queue on it.

    // Primary key, generated by a PostgreSQL identity column
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // Event details
    @Column(nullable = false)
    private String title;

    @Column(length = 2000)
    private String description;
    
    private Integer organiserId;            // user id of the organiser who owns the event
    
    private String location;
    
    private LocalDateTime startDateTime;    // UTC
    
    private LocalDateTime endDateTime;      // UTC, after startDateTime

    // Booking-related fields

    // Places still available; the signup SQL decrements it while the event row is locked
    @Column(nullable = false)
    private Integer capacity;

    private Integer maxCapacity;             // initial capacity; signups so far = maxCapacity - capacity

    private Integer minSignUps;              // minimum signups required before expiresAt

    private LocalDateTime expiresAt;         // UTC; event is auto-cancelled if minSignUps is not reached

    private BigDecimal ticketPrice;         // copied into Booking.totalAmount on signup
    
    private String currency;                // e.g. "SGD"

    // "ACTIVE" allows signups; any other value blocks them (checked by the service and by the signup SQL)
    @Column(nullable = false)
    private String status;

    // Audit timestamps (UTC, set by EventService)
    private LocalDateTime createdAt;
    
    private LocalDateTime updatedAt;

    /* No-args constructor required by JPA; instantiation by reflection so 
        creating instances of classes (objects/entities) dynamically at runtime using their metadata 
        (names, type signatures, or structural definitions), rather than hardcoding their creation at compile time. */
    public Event() {
    }

    // Getters and setters
    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public Integer getOrganiserId() {
        return organiserId;
    }

    public void setOrganiserId(Integer organiserId) {
        this.organiserId = organiserId;
    }

    public String getLocation() {
        return location;
    }

    public void setLocation(String location) {
        this.location = location;
    }

    public LocalDateTime getStartDateTime() {
        return startDateTime;
    }

    public void setStartDateTime(LocalDateTime startDateTime) {
        this.startDateTime = startDateTime;
    }

    public LocalDateTime getEndDateTime() {
        return endDateTime;
    }

    public void setEndDateTime(LocalDateTime endDateTime) {
        this.endDateTime = endDateTime;
    }

    public Integer getCapacity() {
        return capacity;
    }

    public void setCapacity(Integer capacity) {
        this.capacity = capacity;
    }

    public Integer getMaxCapacity() {
        return maxCapacity;
    }

    public void setMaxCapacity(Integer maxCapacity) {
        this.maxCapacity = maxCapacity;
    }

    public Integer getMinSignUps() {
        return minSignUps;
    }

    public void setMinSignUps(Integer minSignUps) {
        this.minSignUps = minSignUps;
    }

    public LocalDateTime getExpiresAt() {
        return expiresAt;
    }

    public void setExpiresAt(LocalDateTime expiresAt) {
        this.expiresAt = expiresAt;
    }

    public BigDecimal getTicketPrice() {
        return ticketPrice;
    }

    public void setTicketPrice(BigDecimal ticketPrice) {
        this.ticketPrice = ticketPrice;
    }

    public String getCurrency() {
        return currency;
    }

    public void setCurrency(String currency) {
        this.currency = currency;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}
